"""
Simulated Sensor Monitoring View
Displays telemetry across Pressure, Flow, Acoustic, Vibration, and Reservoir-Level sensors.
Highlights data-quality health flags and clearly identifies synthetic simulation origins.
"""
import streamlit as st
import pandas as pd
import plotly.graph_objects as go
from datetime import datetime, timedelta

import config
from models.sensor import SensorType, SensorHealthStatus
from ui.components import render_disclaimer_banner, render_badge, apply_chart_theme
from simulation.scenarios import SimulationScenarioManager


def render_sensor_view(db, simulator):
    st.markdown("## 📡 Simulated Sensor Telemetry Monitoring")
    render_disclaimer_banner()

    st.markdown("""
    <div style="background: #eff6ff; border: 1px solid #bfdbfe; border-radius: 8px; padding: 12px 16px; margin-bottom: 20px; font-size: 13px; color: #1e40af;">
        <strong>SYNTHETIC TELEMETRY NOTICE:</strong> All telemetry displayed below is generated by mathematical simulation models 
        incorporating diurnal consumption rhythms and hydraulic friction equations. 
        Sensor health tags (<span style="font-weight:600;">HEALTHY, FROZEN, MISSING, DELAYED, UNREALISTIC, DEGRADED</span>) demonstrate 
        the system's ability to screen out telemetry artifacts before algorithmic leak detection.
    </div>
    """, unsafe_allow_html=True)

    segments = db.get_all_segments()
    reservoirs = db.get_all_reservoirs()

    # Get active scenario overrides
    current_scen_key = st.session_state.get("current_scenario", "NORMAL_OPERATION")
    scen_info = SimulationScenarioManager.get_scenario(current_scen_key)
    overrides = scen_info.get("overrides", {})

    # Generate recent 12-hour historical readings for inspection
    history_readings = simulator.generate_historical_series(
        segments=segments,
        reservoirs=reservoirs,
        hours_back=12,
        interval_minutes=30,
        scenario_overrides=overrides,
    )
    df_readings = pd.DataFrame(history_readings)

    # --- Filters ---
    st.markdown("### 🔍 Telemetry Stream Filters")
    f1, f2, f3 = st.columns(3)

    with f1:
        sensor_type_filter = st.selectbox(
            "Sensor Modality:",
            options=["ALL", SensorType.PRESSURE.value, SensorType.FLOW.value, SensorType.ACOUSTIC.value, SensorType.VIBRATION.value, SensorType.RESERVOIR_LEVEL.value],
            index=0,
        )

    with f2:
        seg_options = ["ALL"] + [s["segment_id"] for s in segments]
        segment_filter = st.selectbox("Pipeline Segment:", options=seg_options, index=0)

    with f3:
        health_options = ["ALL", "HEALTHY", "DEGRADED", "FROZEN", "MISSING", "DELAYED", "UNREALISTIC"]
        health_filter = st.selectbox("Sensor Health Status:", options=health_options, index=0)

    # Apply filters
    filtered_df = df_readings.copy()
    if sensor_type_filter != "ALL":
        filtered_df = filtered_df[filtered_df["sensor_type"] == sensor_type_filter]
    if segment_filter != "ALL":
        filtered_df = filtered_df[filtered_df["segment_id"] == segment_filter]
    if health_filter != "ALL":
        filtered_df = filtered_df[filtered_df["health_status"] == health_filter]

    # --- Chart Visualization for Filtered Segment or Modality ---
    st.markdown("### 📈 Telemetry Time-Series")
    if not filtered_df.empty and segment_filter != "ALL" and sensor_type_filter != "ALL":
        fig = go.Figure()
        chart_data = filtered_df.sort_values("timestamp")
        fig.add_trace(go.Scatter(
            x=chart_data["timestamp"],
            y=chart_data["value"],
            mode="lines+markers",
            name=f"{segment_filter} — {sensor_type_filter}",
            line={"color": "#0284c7", "width": 2},
            marker={"size": 5},
        ))
        fig = apply_chart_theme(fig, title=f"{sensor_type_filter} Telemetry on {segment_filter}")
        st.plotly_chart(fig, use_container_width=True)
    else:
        # Comparative overview across segments for selected modality
        target_modality = sensor_type_filter if sensor_type_filter != "ALL" else SensorType.PRESSURE.value
        mod_df = df_readings[df_readings["sensor_type"] == target_modality].sort_values("timestamp")

        fig_all = go.Figure()
        colors = ["#0284c7", "#0ea5e9", "#059669", "#d97706", "#dc2626", "#7c3aed", "#b45309", "#0d9488"]
        unique_segs = mod_df["segment_id"].unique()[:6]

        for i, s_id in enumerate(unique_segs):
            sub = mod_df[mod_df["segment_id"] == s_id]
            fig_all.add_trace(go.Scatter(
                x=sub["timestamp"],
                y=sub["value"],
                mode="lines",
                name=s_id,
                line={"color": colors[i % len(colors)], "width": 2},
            ))

        fig_all = apply_chart_theme(fig_all, title=f"Comparative {target_modality} Trends Across Segments (Recent 12h)")
        st.plotly_chart(fig_all, use_container_width=True)

    # --- Telemetry Data Table ---
    st.markdown(f"### 📋 Telemetry Records ({len(filtered_df)} Readings)")
    display_df = filtered_df[["timestamp", "segment_id", "station_id", "sensor_type", "value", "unit", "health_status", "flag_notes"]].head(150)
    st.dataframe(display_df, use_container_width=True, hide_index=True)
